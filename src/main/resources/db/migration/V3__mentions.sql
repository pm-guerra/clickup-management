-- Mentions of the app's own user (Octo bot) in task comments and chat channels. Only ids are stored, never the
-- message text; whoever handles a mention reads the text from ClickUp. forwarded_at is set once it's been handed on.
create table octo_mention (
    id                bigint generated by default as identity primary key,
    source            varchar(16)              not null,
    item_id           varchar(64)              not null,
    task_id           varchar(64),
    channel_id        varchar(64),
    parent_message_id varchar(64),
    author_user_id    bigint,
    mentioned_at      timestamp with time zone not null,
    recorded_at       timestamp with time zone not null,
    forwarded_at      timestamp with time zone,
    constraint uk_octo_mention_item unique (source, item_id)
);

-- Per watched chat channel: when polling started (older messages are never treated as new mentions).
create table chat_poll_state (
    channel_id varchar(64)              primary key,
    started_at timestamp with time zone not null
);

-- Reply counts of recent thread starters, so replies are only fetched when a thread got new ones.
create table chat_thread_state (
    message_id    varchar(64) primary key,
    channel_id    varchar(64) not null,
    replies_count integer     not null
);
